local M = assert(loadfile(assert(arg[1]) .. '/plugin/lib/jobs.luau'))()
local jobs = M.new()
local first = assert(jobs.begin('attachment', { backend = 'codex', session = 'one', navigation = 1 }))
assert(not jobs.begin('export', {}) and jobs.pending() == 'attachment')
assert(jobs.current(first, 'codex', 'one', 1))
assert(not jobs.current(first, 'opencode', 'one', 1))
assert(not jobs.current(first, 'codex', 'two', 1))
assert(not jobs.current(first, 'codex', 'one', 2), 'manual reopen must obsolete focus restoration')
assert(jobs.finish(first) and not jobs.finish(first), 'completion must be delivered once')
local next = assert(jobs.begin('export', {}))
assert(not jobs.finish(first) and jobs.pending() == 'export', 'late completion cannot clear a newer operation')
assert(jobs.finish(next) and jobs.pending() == nil)
print('Interactive job ownership, navigation and once-only completion: passed')
